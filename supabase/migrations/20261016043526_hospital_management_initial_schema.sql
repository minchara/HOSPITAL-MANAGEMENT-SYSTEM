-- Initial schema for the hospital management system.
-- RLS is enabled and API access is denied until an authenticated staff access
-- model and matching policies are defined.

create table public.patients (
  id bigint generated by default as identity primary key,
  name text not null,
  age smallint check (age between 0 and 130),
  gender text,
  phone text,
  disease text,
  created_at timestamptz not null default now()
);

create table public.appointments (
  id bigint generated by default as identity primary key,
  patient_id bigint not null references public.patients(id) on delete restrict,
  doctor text,
  appointment_date date,
  appointment_time time,
  dept text,
  status text not null default 'Scheduled'
    check (status in ('Scheduled', 'Completed', 'Cancelled')),
  created_at timestamptz not null default now()
);

create table public.bills (
  id bigint generated by default as identity primary key,
  patient_id bigint not null references public.patients(id) on delete restrict,
  amount numeric(12, 2) not null check (amount >= 0),
  status text not null default 'Paid'
    check (status in ('Paid', 'Unpaid', 'Pending')),
  created_at timestamptz not null default now()
);

create index appointments_patient_id_idx on public.appointments(patient_id);
create index appointments_appointment_date_idx on public.appointments(appointment_date);
create index bills_patient_id_idx on public.bills(patient_id);

alter table public.patients enable row level security;
alter table public.appointments enable row level security;
alter table public.bills enable row level security;

revoke all privileges on table public.patients, public.appointments, public.bills
  from anon, authenticated;
